out.push("");
out.push(
  "**Finding: every retrieval call ensures its paper's context twice.** `search_paper` ensures each paper in its own auto-index loop, and `retrieveEvidence` ensures it again — before it checks the evidence cache, so even a fully cached retrieval pays it. Six ensures for three calls, above. It is cheap today because `PdfService` caches, but the duplication is real; it is pinned here so it cannot grow quietly.",
);
out.push("");
out.push("## Needs a live flight");
out.push("");
out.push(
  "Nothing above involves a real model. These are the questions only a live flight can answer, and none of them was measured in this phase:",
);
out.push("");
out.push(
  "- **How many rounds a real model takes** for each of these journeys — the scripted counts pin the contract's floor, not a model's behavior.",
);
out.push(
  "- **How often a real model re-reads the same paper** inside one run, and therefore what the evidence cache is actually worth. `repeatedCallsForSameItem` is a floor measured on a journey built to repeat once.",
);
out.push(
  "- **Whether a real model re-authors material it has already finalized**, which the scripted journeys cannot exhibit at all: their material identities are frozen by the script.",
);
out.push(
  "- **Where a real provider's delta cadence sits** between the flowing render rows and the stalled ceiling.",
);
out.push("");
out.push(
  "The live behavior harness (`npm run test:behavior`) costs money and needs the user's credentials, so it was **not** run in this phase — that was a recorded ruling, not an omission.",
);
out.push("");

process.stdout.write(out.join("\n"));
